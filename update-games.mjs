// Pulls live data for the portfolio from the public Roblox API.
// Usage:  node update-games.mjs
// Writes games-data.js (loaded by index.html) and saves thumbnails into assets/games/.
// To add a game, put its universe ID in UNIVERSES (find it with the search below or
// from https://apis.roblox.com/universes/v1/places/<placeId>/universe).
import { writeFile, mkdir } from 'node:fs/promises';

const UNIVERSES = [10770806914, 10772159183, 10773748361];

const get = async url => {
  const r = await fetch(url, { headers: { accept: 'application/json' } });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
};
const ids = UNIVERSES.join(',');
const [games, votes, icons, thumbs] = await Promise.all([
  get(`https://games.roblox.com/v1/games?universeIds=${ids}`),
  get(`https://games.roblox.com/v1/games/votes?universeIds=${ids}`),
  get(`https://thumbnails.roblox.com/v1/games/icons?universeIds=${ids}&size=512x512&format=Png`),
  get(`https://thumbnails.roblox.com/v1/games/multiget/thumbnails?universeIds=${ids}&size=768x432&format=Png&countPerUniverse=1`),
]);

await mkdir('assets/games', { recursive: true });
const save = async (url, path) => {
  if (!url) return null;
  const r = await fetch(url);
  if (!r.ok) return null;
  await writeFile(path, Buffer.from(await r.arrayBuffer()));
  return path;
};
const slugify = s => s.replace(/\[[^\]]*\]/g, '').trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
// strip emoji/decoration so names and copy read cleanly
const clean = s => s.replace(/\[[^\]]*\]/g, '').replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\u{200D}\u{2B00}-\u{2BFF}\u{1F1E6}-\u{1F1FF}]/gu, '').replace(/�/g, '').replace(/[ \t]+/g, ' ').trim();

const out = [];
for (const id of UNIVERSES) {
  const g = games.data.find(x => x.id === id);
  if (!g) { console.warn('missing universe', id); continue; }
  const v = votes.data.find(x => x.id === id) || { upVotes: 0, downVotes: 0 };
  const slug = slugify(g.name);
  const icon = await save(icons.data.find(x => x.targetId === id)?.imageUrl, `assets/games/${slug}-icon.png`);
  const thumb = await save(thumbs.data.find(x => x.universeId === id)?.thumbnails?.[0]?.imageUrl, `assets/games/${slug}.png`);
  const lines = clean(g.description).split('\n').map(l => l.trim()).filter(Boolean);
  const howIdx = lines.findIndex(l => /^how to play/i.test(l));
  out.push({
    slug, universeId: id, placeId: g.rootPlaceId,
    name: clean(g.name), studio: g.creator.name,
    created: g.created, updated: g.updated,
    playing: g.playing, visits: g.visits, favorites: g.favoritedCount,
    likes: v.upVotes + v.downVotes ? Math.round(v.upVotes / (v.upVotes + v.downVotes) * 100) : null,
    intro: lines.slice(0, howIdx > 0 ? howIdx : 2).filter(l => !/^code:/i.test(l)).join(' ') || 'Live on Roblox.',
    howTo: howIdx >= 0 ? lines.slice(howIdx + 1, howIdx + 7) : [],
    icon, thumb,
  });
}

const stamp = new Date().toISOString();
await writeFile('games-data.js',
  `// Generated by update-games.mjs on ${stamp}. Do not edit by hand; rerun the script.\n` +
  `window.MT_GAMES = ${JSON.stringify(out, null, 2)};\nwindow.MT_GAMES_UPDATED = ${JSON.stringify(stamp)};\n`);
console.log(`Wrote ${out.length} games to games-data.js`);
for (const g of out) console.log(` - ${g.name} (${g.studio}): ${g.playing} playing, ${g.visits} visits, ${g.likes}% likes`);
