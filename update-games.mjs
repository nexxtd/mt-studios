// Saves a snapshot of the portfolio to games-data.js.
// The live site reads games from /api/games (managed in /admin → Games); this snapshot
// is only shown until that answers, or if it can't be reached (e.g. index.html opened
// from disk). Usage:  node update-games.mjs
import { writeFile } from 'node:fs/promises';
import { fetchGames, slugify } from './api/_lib/roblox.js';
import { SEED_UNIVERSES } from './api/_lib/games-store.js';

const live = await fetchGames(SEED_UNIVERSES);
const used = new Set();
const out = SEED_UNIVERSES.map(id => live.find(g => g.universeId === id)).filter(Boolean).map(g => {
  let slug = slugify(g.name);
  if (used.has(slug)) slug = `${slug}-${g.universeId}`;
  used.add(slug);
  return { slug, ...g };
});

const stamp = new Date().toISOString();
await writeFile('games-data.js',
  `// Generated by update-games.mjs on ${stamp}. Do not edit by hand; rerun the script.\n` +
  `window.MT_GAMES = ${JSON.stringify(out, null, 2)};\nwindow.MT_GAMES_UPDATED = ${JSON.stringify(stamp)};\n`);
console.log(`Wrote ${out.length} games to games-data.js`);
for (const g of out) console.log(` - ${g.name} (${g.studio}): ${g.playing} playing, ${g.visits} visits`);
